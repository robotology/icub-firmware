#!/usr/bin/env python3
"""
gen_sgact_spec.py - sgact_panel.toml -> matlab/sgact_spec.m and matlab/sgact_modes_dispatch.m (for the Speedgoat:
MATLAB code generation cannot read a TOML file). build_sgact_lib runs it; it can also be run by hand:

    py tools/gen_sgact_spec.py                         (from the folder simulink: ../sgact_panel.toml -> ./matlab)
    py tools/gen_sgact_spec.py --toml X.toml --out matlab --pymodes ../emul/sgact_modes.py

It checks that every mode has its matlab/sgact_mode_<name>.m and, if sgact_modes.py is found, its mode_<name>()
(or speedgoat_only = true). Exit code 0 ok, 1 error.
"""

import argparse
import importlib.util
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(_HERE))), "shared"))   # host/shared
import sgact_spec  # noqa: E402


def mfmt(v):
    return repr(float(v)) if v != int(v) else f"{int(v)}"


def gen_spec(spec):
    n = len(spec.modes)
    mp = spec.max_params
    pmin = [[0.0] * mp for _ in range(n)]
    pmax = [[0.0] * mp for _ in range(n)]
    pscale = [[1.0] * mp for _ in range(n)]
    for i, m in enumerate(spec.modes):
        for k, p in enumerate(m.params):
            pmin[i][k], pmax[i][k], pscale[i][k] = p.min, p.max, p.scale

    def mat(rows):
        return "[" + "; ...\n                   ".join(" ".join(f"{mfmt(v):>6}" for v in r) for r in rows) + "]"

    lines = [
        "function s = sgact_spec()",
        f"%SGACT_SPEC generated by tools/gen_sgact_spec.py from {os.path.basename(spec.path)}: DO NOT EDIT.",
        "%   Edit sgact_panel.toml and run build_sgact_lib (or the generator) again.",
        "%   modes: " + ", ".join(f"{m.name}={m.id}" for m in spec.modes),
        f"    s.CRC = uint32({spec.crc});          % 0x{spec.crc:08X}: CRC32 of the TOML (CRLF as LF), it travels in every CTL",
        f"    s.VERSION = {spec.version};",
        f"    s.KEEPALIVE = {mfmt(spec.keepalive)};",
        f"    s.MAX_PARAMS = {mp};",
    ]
    for name in sgact_spec.DEVICE_NAMES:
        lines.append(f"    s.DEV_{name.upper()} = {1 << spec.devices[name] if name in spec.devices else 0};")
    lines.append(f"    s.DEV_ALL = {sum(1 << b for b in spec.devices.values())};")
    for name in sgact_spec.ACTION_NAMES:
        lines.append(f"    s.ACT_{name.upper()} = {spec.actions[name]};")
    lines += [
        f"    s.NMODES = {n};",
        "    s.MODE_ID = [" + " ".join(str(m.id) for m in spec.modes) + "];",
        "    s.MODE_NEEDS = [" + " ".join(str(m.needs_mask) for m in spec.modes) + "];      % device mask",
        "    s.MODE_NPARAMS = [" + " ".join(str(len(m.params)) for m in spec.modes) + "];",
        "    s.MODE_CMODE = [" + " ".join(str(m.controlmode) for m in spec.modes) + "];      % control mode of the motor_macro, 0 none",
        "    s.MODE_CUBEON = [" + " ".join(str(int(m.cube_enable)) for m in spec.modes) + "];      % 1: it enables the motor_cubemars at the start, else disables it",
        "    s.MODE_IMPL = [" + " ".join("2" if m.impl == "simulink" else "1" for m in spec.modes) + "];      % 1 matlab (standard modes), 2 simulink (USER CONTROL)",
        f"    s.PARAM_MIN = {mat(pmin)};",
        f"    s.PARAM_MAX = {mat(pmax)};",
        "    % the parameter in the unit of the TOML (checked against min max) times PARAM_SCALE: the value in SI that the mode sees",
        f"    s.PARAM_SCALE = {mat(pscale)};",
        "    % the config of the motor_macro in the TOML, in the order of the CTL (the panel sends it, this is its default):",
        "    % " + " ".join(sgact_spec.MMCFG_NAMES),
        "    s.MMCFG = [" + " ".join(mfmt(v) for v in spec.mmcfg) + "];",
        "end",
        "",
    ]
    return "\n".join(lines)


def gen_dispatch(spec):
    lines = [
        "function [valid, sp, done] = sgact_modes_dispatch(mode, phase, p, t, fb)",
        f"%SGACT_MODES_DISPATCH generated by tools/gen_sgact_spec.py from {os.path.basename(spec.path)} (crc 0x{spec.crc:08X}): DO NOT EDIT.",
        "%   the mode with id mode: phase 1 run, 2 stop; p: its parameters (1 x MAX_PARAMS); t: s since the phase started",
        "%   only the modes w/ impl = matlab: the ones w/ impl = simulink are subsystems of USER CONTROL (sgact_sync_modes)",
        "%   valid: there is a MIT for the motor_cubemars (sp(1:5)), sp = [kp kd pos vel torque mmtarget], done: the stop is over",
        "    valid = false;",
        "    sp = zeros(1, 6);",
        "    done = true;",
        "    switch mode",
    ]
    for m in spec.modes:
        if m.impl == "matlab":
            lines += [f"        case {m.id}", f"            [valid, sp, done] = sgact_mode_{m.name}(phase, p, t, fb);"]
    lines += ["    end", "end", ""]
    return "\n".join(lines)


def gen_info(spec):
    """the list of the modes for the build scripts (sgact_sync_modes): not for the generated code, it has cell arrays"""
    rows = ";\n        ".join(f"'{m.name}', {m.id}, '{m.impl}'" for m in spec.modes)
    return "\n".join([
        "function m = sgact_modes_info()",
        f"%SGACT_MODES_INFO generated by tools/gen_sgact_spec.py from {os.path.basename(spec.path)} (crc 0x{spec.crc:08X}): DO NOT EDIT.",
        "%   the modes of the TOML for the build scripts: name, id, impl (matlab / simulink). not for the generated code",
        "    c = {",
        f"        {rows}",
        "    };",
        "    m = struct('name', c(:, 1), 'id', c(:, 2), 'impl', c(:, 3));",
        "end",
        "",
    ])


def main():
    ap = argparse.ArgumentParser(description="sgact_panel.toml -> matlab/sgact_spec.m, matlab/sgact_modes_dispatch.m")
    root = os.path.dirname(_HERE)
    ap.add_argument("--toml", default=os.path.join(os.path.dirname(root), sgact_spec.SPEC_NAME))
    ap.add_argument("--out", default=os.path.join(root, "matlab"))
    ap.add_argument("--pymodes", default=None, help="sgact_modes.py of the daemon, to check that it has every mode")
    args = ap.parse_args()
    try:
        spec = sgact_spec.load(args.toml)
    except (sgact_spec.SpecError, KeyError, ValueError, TypeError) as e:
        print(f"[error] {e}")
        return 1

    missing = [m.name for m in spec.modes if m.impl == "matlab" and not os.path.isfile(os.path.join(args.out, f"sgact_mode_{m.name}.m"))]
    if missing:
        print(f"[error] no matlab/sgact_mode_<name>.m for: {', '.join(missing)}")
        return 1

    pymodes = args.pymodes
    if pymodes is None:
        for c in (os.path.join(root, "..", "emul", "sgact_modes.py"),):
            if os.path.isfile(c):
                pymodes = c
                break
    if pymodes and os.path.isfile(pymodes):
        s = importlib.util.spec_from_file_location("sgact_modes", pymodes)
        mod = importlib.util.module_from_spec(s)
        s.loader.exec_module(mod)
        nopy = [m.name for m in spec.modes if not m.speedgoat_only and not hasattr(mod, f"mode_{m.name}")]
        if nopy:
            print(f"[error] {pymodes}: no mode_<name>() for: {', '.join(nopy)} (or mark them speedgoat_only = true)")
            return 1
    else:
        print("[info] sgact_modes.py of the daemon not found: its modes are not checked")

    for name, text in (("sgact_spec.m", gen_spec(spec)), ("sgact_modes_dispatch.m", gen_dispatch(spec)),
                       ("sgact_modes_info.m", gen_info(spec))):
        target = os.path.join(args.out, name)
        old = open(target, encoding="utf-8").read() if os.path.isfile(target) else None
        if old != text:                     # written only when it changes: no noise in git
            with open(target, "w", newline="\n", encoding="utf-8") as f:
                f.write(text)
    print(f"generated sgact_spec.m, sgact_modes_dispatch.m, sgact_modes_info.m from {spec.path} (crc 0x{spec.crc:08X}, {len(spec.modes)} modes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
