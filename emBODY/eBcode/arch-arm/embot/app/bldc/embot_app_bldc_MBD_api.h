    struct State
    {        
        constexpr State() = default;
        
        explicit State(ExtY_iterative_motion_controller_T &out)
        {
            load(out);         
        }
        
        void load(ExtY_iterative_motion_controller_T &out)
        {
            for(uint8_t m=0; m<nmot; m++)
            {
                actcfg[m] = fieldptr(out.ConfigurationParameters, m);
                messages[m] = fieldptr(out.Messages, m);
                messagesflags[m] = fieldptr(out.MessagesFlags, m);
           }           
        }
        
        bool isvalid() const
        {
            return nullptr != actcfg[0];
        }
        
    public:
        static constexpr uint8_t nmot {maxMOTORs};
        ActuatorConfiguration* actcfg[nmot] {};
        BUS_MESSAGES_TX* messages[nmot] {};
        BUS_STATUS_TX* messagesflags[nmot] {};            
    };


