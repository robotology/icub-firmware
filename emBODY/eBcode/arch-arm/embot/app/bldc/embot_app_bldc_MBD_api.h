namespace embot::app::bldc::mbd::interface {
    
    // helpers which manage a field of the generated code that can be either T[N] or a plain T
    
    // number of items in the field: N if it is T[N], 1 if it is a plain T
    template<typename F>
    constexpr size_t fieldcount = std::is_array_v<F> ? std::extent_v<F> : 1;
 
    // pointer to the i-th item of the field, or nullptr if i is out of range
    template<typename F>
    constexpr std::remove_extent_t<F>* fieldptr(F &f, size_t i)
    {
        if constexpr (std::is_array_v<F>)
        {
            return (i < std::extent_v<F>) ? &f[i] : nullptr;
        }
        else
        {
            return (0 == i) ? &f : nullptr;
        }
    }
    
    // reference to the i-th item of the field.
    // the caller must guarantee i < fieldcount<F>: for a plain T any index returns the only item.
    template<typename F>
    constexpr std::remove_extent_t<F>& fieldref(F &f, size_t i)
    {
        if constexpr (std::is_array_v<F>)
        {
            return f[i];
        }
        else
        {
            static_cast<void>(i);
            return f;
        }
    }
    

    // the number of motors as generated by matlab is deduced at compile time from the outputs
    constexpr size_t maxMOTORs {fieldcount<decltype(ExtY_iterative_motion_controller_T::FOCOutputs_h)>};

    
    // all the fields we use must agree on the number of motors
    static_assert(fieldcount<decltype(ExtY_iterative_motion_controller_T::ConfigurationParameters)> == maxMOTORs, "inconsistent number of motors in generated code");
    static_assert(fieldcount<decltype(ExtY_iterative_motion_controller_T::MessagesFlags)> == maxMOTORs, "inconsistent number of motors in generated code");
}


