#!/usr/bin/env python3
# make_api.py: it generates api/cmsisrtx.h, the single header that exposes the cmsisrtx library to the users.
# it merges, verbatim, the two public headers that the application needs (cmsis_os2.h, os_tick.h: they keep their
# own include guards, so including the originals too is harmless) and adds the constants that RTX keeps in rtx_os.h
# (sizes of the control blocks, needed to create the RTOS objects with user memory). the sizes are checked against the
# real rtx_os.h at compile time by cfg/cmsisrtx_cfg.c, so a new RTX version cannot silently change them.
# usage: python3 make_api.py        (from any folder)

import pathlib

root = pathlib.Path(__file__).resolve().parents[2]
osh = root / "src/CMSIS_6/CMSIS/RTOS2/Include/cmsis_os2.h"
tickh = root / "src/CMSIS_6/CMSIS/RTOS2/Include/os_tick.h"
out = root / "api/cmsisrtx.h"

banner = '''/*
 * cmsisrtx.h
 *
 * The single API header of the cmsisrtx library: CMSIS-RTX 5.9.1 (kernel, unmodified) + CMSIS-RTOS2 API 2.3.0 +
 * the CMSIS OS Tick API (SysTick implementation of CMSIS 6.4.0). Link the cmsisrtx_cm4.lib / cmsisrtx_cm7.lib.
 *
 * THIS FILE IS GENERATED by src/extra/make_api.py: do not edit it. It contains, verbatim, cmsis_os2.h and os_tick.h
 * (Apache-2.0, (c) Arm Limited) followed by the section "cmsisrtx extras" at the end.
 */

#pragma once

'''

extras = '''

/* ------------------------------------------------------------------------------------------------------------
 * cmsisrtx extras
 * ------------------------------------------------------------------------------------------------------------
 * RTX lets the user provide the memory of every object (the control block, the stack, the queue storage), so that
 * the objects can be created at run time, e.g. with new, instead of being pre-allocated by RTX_Config.h.
 * The sizes below are the ones of rtx_os.h (32-bit Cortex-M). cfg/cmsisrtx_cfg.c verifies them at compile time.
 * The memory must be 4-byte aligned (stacks: 8-byte aligned and with a size multiple of 8).
 */

#define CMSISRTX_VERSION                    "5.9.1"

#define CMSISRTX_THREAD_CB_SIZE             80U
#define CMSISRTX_TIMER_CB_SIZE              32U
#define CMSISRTX_EVENTFLAGS_CB_SIZE         16U
#define CMSISRTX_MUTEX_CB_SIZE              28U
#define CMSISRTX_SEMAPHORE_CB_SIZE          16U
#define CMSISRTX_MEMORYPOOL_CB_SIZE         36U
#define CMSISRTX_MESSAGEQUEUE_CB_SIZE       52U

#define CMSISRTX_STACK_ALIGNMENT            8U
#define CMSISRTX_STACK_MINSIZE              72U     /* the minimum accepted by osThreadNew() */

/* bytes of the storage (mq_mem) of a message queue / of a memory pool (mp_mem) */
#define CMSISRTX_MESSAGEQUEUE_MEM_SIZE(msg_count, msg_size) \\
    (4U*(msg_count)*(3U+(((msg_size)+3U)/4U)))
#define CMSISRTX_MEMORYPOOL_MEM_SIZE(block_count, block_size) \\
    (4U*(block_count)*(((block_size)+3U)/4U))

/* The fixed attributes of the objects (osXxxAttr_t) are built by the user code with these sizes, e.g.
 *   osMutexAttr_t attr {}; attr.cb_mem = new uint32_t[CMSISRTX_MUTEX_CB_SIZE/4]; attr.cb_size = CMSISRTX_MUTEX_CB_SIZE;
 * The application must provide: osRtxIdleThread() and osRtxErrorNotify() (weak defaults are in cfg/RTX_Config.c),
 * and the global SystemCoreClock (the OS Tick uses it to program the SysTick).
 */

/* ------------------------------------------------------------------------------------------------------------
 * Run-time configuration (CMSISRTX_RUNTIME_CONFIG, default on: see rtx_os.h)
 * ------------------------------------------------------------------------------------------------------------
 * The kernel reads these values only in osKernelStart(): they can be set after the kernel initialisation (which
 * happens before main()) and before the start. Everything is optional: a field set to 0 / NULL keeps the build-time
 * value of cfg/RTX_Config.h. The memory is provided by the caller (e.g. calloc: it must stay valid forever).
 */
typedef struct
{
    uint32_t tick_freq;             /* Hz. Must be reachable by the SysTick: SystemCoreClock/tick_freq <= 2^24 */
    void *idle_stack_mem;           /* 8-byte aligned. both memory and size, or both 0 */
    uint32_t idle_stack_size;       /* multiple of 8, >= CMSISRTX_STACK_MINSIZE */
    void *timer_stack_mem;          /* as idle */
    uint32_t timer_stack_size;
    uint32_t timer_priority;        /* an osPriority_t between osPriorityLow and osPriorityRealtime7. 0: unchanged */
    void *timer_mq_mem;             /* 4-byte aligned: storage of the queue of the timer thread. */
    uint32_t timer_mq_mem_size;     /* >= CMSISRTX_MESSAGEQUEUE_MEM_SIZE(timer_mq_msgs, CMSISRTX_TIMER_MSG_SIZE) */
    uint32_t timer_mq_msgs;         /* how many timer callbacks can be pending */
    void **isr_queue_mem;           /* 4-byte aligned: queue of the ISR post processing */
    uint32_t isr_queue_size;        /* number of entries (void*): >= 4 */
} cmsisrtx_config_t;

#define CMSISRTX_TIMER_MSG_SIZE             8U      /* sizeof(osRtxTimerFinfo_t) */

#define CMSISRTX_CONFIG_OK                  0
#define CMSISRTX_CONFIG_ERR_PARAM           (-1)    /* a value is not valid: nothing was changed */
#define CMSISRTX_CONFIG_ERR_STATE           (-2)    /* the kernel is already running */
#define CMSISRTX_CONFIG_UNSUPPORTED         (-3)    /* built with CMSISRTX_RUNTIME_CONFIG=0 */

#ifdef __cplusplus
extern "C" {
#endif
extern int32_t cmsisrtx_config_set(const cmsisrtx_config_t *config);
#ifdef __cplusplus
}
#endif
'''

o = banner + tickh.read_text() + "\n" + osh.read_text() + extras
out.write_text(o)
print("written", out, len(o.splitlines()), "lines")
