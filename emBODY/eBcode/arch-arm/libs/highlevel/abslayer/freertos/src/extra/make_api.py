# It fills the folder api/ of the freertos lib with what an application needs to use the lib:
#   - src/extra/freertos_api.h            the API of the lib (the only header to include)
#   - cfg/FreeRTOSConfig.h                the configuration used to build the lib (it must be the same)
#   - the headers of the kernel and portmacro.h of the port used by the lib (GCC/ARM_CM4F), but only those reachable
#     from freertos_api.h through #include "..." (also the ones under #if: a few more than needed, never one less)
#
# Run it (from any folder) when the kernel, the port, FreeRTOSConfig.h or freertos_api.h change:
#   python3 src/extra/make_api.py
# It is not part of the build.

import pathlib
import re

here = pathlib.Path(__file__).resolve().parent          # src/extra
root = here.parent.parent                               # the freertos lib folder
api = root / "api"
kernel = root / "src" / "FreeRTOS-Kernel"
port = kernel / "portable" / "GCC" / "ARM_CM4F"

header = (
    "/* generated by src/extra/make_api.py from the sources of the freertos lib: do not edit, edit the source and run it again */\n"
)

def copy(src: pathlib.Path, dst: pathlib.Path, mark: bool) -> None:
    text = src.read_text(encoding="utf-8")
    if mark:
        text = header + text
    dst.write_text(text, encoding="utf-8", newline="\n")

def main() -> None:
    api.mkdir(exist_ok=True)
    # remove the old headers, so that a header removed from the kernel does not stay here
    for old in api.glob("*.h"):
        old.unlink()

    copy(here / "freertos_api.h", api / "freertos_api.h", True)
    copy(root / "cfg" / "FreeRTOSConfig.h", api / "FreeRTOSConfig.h", True)
    # the headers of the kernel reachable from freertos_api.h, searched as the compiler would do in the api/ folder
    sources = {h.name: h for h in (kernel / "include").glob("*.h")}
    sources["portmacro.h"] = port / "portmacro.h"
    sources["FreeRTOSConfig.h"] = root / "cfg" / "FreeRTOSConfig.h"
    included = re.compile(r'^\s*#\s*include\s+"([^"]+)"', re.MULTILINE)
    todo = [here / "freertos_api.h"]
    seen = set()
    while todo:
        f = todo.pop()
        for name in included.findall(f.read_text(encoding="utf-8")):
            if (name not in seen) and (name in sources):
                seen.add(name)
                todo.append(sources[name])
    for name in sorted(seen - {"FreeRTOSConfig.h"}):
        copy(sources[name], api / name, False)

    names = sorted(p.name for p in api.glob("*.h"))
    print(f"make_api.py: {len(names)} headers written in {api}")
    for n in names:
        print(f"  {n}")

if __name__ == "__main__":
    main()
